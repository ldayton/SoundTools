"""Prepare the CC BY 4.0 bitKlavier Piano Bar recordings for DoReGo.
Run: python3 scripts/setup-bitklavier.py [path/to/downloaded.zip]
Requires ffmpeg. Downloads the original archive if no path is supplied.
"""
from pathlib import Path
import concurrent.futures, hashlib, json, re, subprocess, sys, urllib.request, zipfile

root = Path(__file__).resolve().parents[1]
url = 'https://archive.org/download/bitKlavierGrand_PianoBar_44k16b/bitKlavierGrand_PianoBar_44k16b.zip'
archive = Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'work/bitklavier-piano-bar.zip'
archive.parent.mkdir(parents=True, exist_ok=True)
if not archive.exists():
    urllib.request.urlretrieve(url, archive)
out = root / 'public/samples/bitklavier'
out.mkdir(parents=True, exist_ok=True)
notes = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}
with zipfile.ZipFile(archive) as z:
    entries = []
    for name in z.namelist():
        match = re.fullmatch(r'([A-G])([#b]?)(-?\d+)v(\d+)\.wav', Path(name).name, re.I)
        if not match or '/__MACOSX/' in name or name.startswith('__MACOSX/'):
            continue
        note, accidental, octave, layer = match.groups()
        midi = 12 * (int(octave) + 1) + notes[note.upper()] + {'': 0, '#': 1, 'b': -1}[accidental]
        entries.append((name, midi, int(layer)))
    if len(entries) < 400:
        raise RuntimeError(f'Unexpected source layout: only {len(entries)} main samples')
    def convert(entry):
        name, midi, layer = entry
        target = out / f'{midi}-v{layer}.flac'
        if not target.exists():
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', 'pipe:0', '-c:a', 'flac', str(target)], input=z.read(name), check=True)
        return {'midi': midi, 'layer': layer, 'file': target.name}
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        samples = sorted(pool.map(convert, entries), key=lambda s: (s['layer'], s['midi']))
(root / 'src/bitklavier-samples.ts').write_text('// Generated by scripts/setup-bitklavier.py; CC BY 4.0.\nexport const BITKLAVIER_SAMPLES = ' + json.dumps(samples) + ' as const;\n')
digest = hashlib.sha256()
with archive.open('rb') as source:
    for chunk in iter(lambda: source.read(1024 * 1024), b''):
        digest.update(chunk)
(out / 'NOTICE.txt').write_text('''bitKlavier Grand - Piano Bar, 44.1 kHz / 16-bit stereo
Steinway Model D, recorded at Princeton Taplin Auditorium, January 2021.
Recorded by Andres Villalta; piano played by Matt Wang; produced by Dan Trueman.
Full credits and original recordings: https://bitklavier.com/the-bitklavier-grand/
License: Creative Commons Attribution 4.0 International
https://creativecommons.org/licenses/by/4.0/
Source: ''' + url + '''
Adaptation: main sustained notes converted losslessly from WAV to FLAC and renamed.
DoReGo maps the 16 recorded layers to equal MIDI velocity ranges and uses nearest-note transposition.
Release, pedal and harmonic samples are not included in this browser adaptation.
Source archive SHA256: ''' + digest.hexdigest() + '\n')
print(f'Prepared {len(samples)} lossless stereo samples.')
